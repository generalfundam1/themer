/* targets.c: built-in targets that are not modules: env, tty, grub. They write
 * system files (tty and grub only as root) that the manifest cannot undo, which is
 * why they are not modules. Everything that touches the user's own config is in
 * modules/. */
#include <limits.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include "themer.h"

/* writes ~/rel; the directories it has to make are noted, so Remove all styles
 * takes them away again once empty */
static int
gen_at(const char *rel, EmitFn fn, const Config *c, const Scheme *s)
{
	char p[PATH_MAX], d[PATH_MAX], *slash;
	char made[8][PATH_MAX];
	int nmade = 0;

	if (path_under_home(p, sizeof p, rel) < 0)
		return -1;
	/* the missing parents, outermost first */
	snprintf(d, sizeof d, "%s", p);
	while ((slash = strrchr(d, '/')) && slash > d && nmade < 8) {
		*slash = '\0';
		if (!access(d, F_OK))
			break;
		snprintf(made[nmade++], PATH_MAX, "%s", d);
	}
	for (int i = 0; i < nmade; i++)
		dirs_note(made[i]);
	return write_gen(p, fn, c, s);
}

/* ---- environment: systemd user environment, from the [environment] settings ---- */

static void
emit_env(FILE *f, const Config *c, const Scheme *s)
{
	(void)s;
	fprintf(f, "# generated by themer\n");
	for (int i = 0; i < c->nenv; i++)
		fprintf(f, "%s=%s\n", c->env[i].name, c->env[i].value);
}

/* The same variables for sessions that systemd does not start: a script to source
 * from the shell profile before the compositor starts. It reads every themer file in
 * environment.d, the modules' included, so it is never behind them. */
void tty_escapes(const Config *c, char *out, size_t n);

static void
emit_env_sh(FILE *f, const Config *c, const Scheme *s)
{
	(void)s;
	fprintf(f, "# generated by themer. Source this from ~/.profile (or .zprofile, .bash_profile)\n"
	           "# when your session is not started through systemd, so programs launched by the\n"
	           "# compositor see the variables: . ~/.config/themer/env.sh\n"
	           "for _f in \"${XDG_CONFIG_HOME:-$HOME/.config}\"/environment.d/*themer*.conf; do\n"
	           "\t[ -r \"$_f\" ] || continue\n"
	           "\twhile IFS= read -r _l || [ -n \"$_l\" ]; do\n"
	           "\t\tcase $_l in ''|'#'*) ;; *=*) export \"$_l\" ;; esac\n"
	           "\tdone < \"$_f\"\n"
	           "done\n"
	           "unset _f _l\n");
	/* on the Linux console itself, the palette at once, with no root needed (the
	 * console's own escape sequences; themer system install makes it stay) */
	{
		char esc[512];

		tty_escapes(c, esc, sizeof esc);
		fprintf(f, "if [ \"$TERM\" = linux ]; then\n\tprintf '%s'\nfi\n", esc);
	}
}

int
gen_env(const Config *c, const Scheme *s)
{
	if (gen_at(".config/environment.d/50-themer.conf", emit_env, c, s) < 0)
		return -1;
	return gen_at(".config/themer/env.sh", emit_env_sh, c, s);
}

/* ---- the console and GRUB ----
 *
 * The console's palette, its font and GRUB's colors are system settings: only root
 * can set them. Every apply, as the user, writes what they should be into
 * ~/.config/themer/system/ (tty.palette in setvtrgb's format, console.conf, grub.conf;
 * the ly module adds ly.conf). Once, as root, "sudo themer system install" sets up a
 * service for the init system running (see system.c) that puts them into effect at
 * boot and on every change: the palette with setvtrgb, the font in /etc/vconsole.conf,
 * the colors in /etc/default/grub (grub-mkconfig when they changed), ly's colors in
 * its config. What it changes in /etc it records key by key and puts back on
 * "sudo themer system remove", or when the user's file goes away (Remove all styles,
 * the ly module off).
 *
 * Without root nothing in /etc is touched. A console you log in to still gets the
 * palette at once: env.sh, sourced from the profile, sets it with the console's own
 * escape sequences when TERM is linux. */

#define SYSTEM_DIR ".config/themer/system"

/* the console palette: the theme's sixteen colors, with the background and the text
 * at 0 and 7, which are what the console draws the screen and plain text in */
static void
console_palette(const Scheme *s, char pal[16][7])
{
	for (int i = 0; i < 16; i++)
		snprintf(pal[i], sizeof pal[i], "%.6s", s->ansi[i]);
	snprintf(pal[0], sizeof pal[0], "%.6s", s->hex[C_BG]);
	snprintf(pal[7], sizeof pal[7], "%.6s", s->hex[C_FG]);
}

static void
emit_palette(FILE *f, const Config *c, const Scheme *s)
{
	char pal[16][7];

	(void)c;
	console_palette(s, pal);
	/* setvtrgb's format: the reds, the greens, the blues, sixteen decimals a line */
	for (int ch = 0; ch < 3; ch++)
		for (int i = 0; i < 16; i++)
			fprintf(f, "%lu%c", (strtoul(pal[i], NULL, 16) >> (16 - 8 * ch)) & 0xff, i < 15 ? ',' : '\n');
}

static void
emit_console(FILE *f, const Config *c, const Scheme *s)
{
	(void)s;
	fprintf(f, "# generated by themer: the console font, put into /etc/vconsole.conf by themer system sync\n"
	           "FONT=%s\n", c->tty_font);
}

static void
emit_grub(FILE *f, const Config *c, const Scheme *s)
{
	(void)s;
	/* GRUB knows sixteen named colors: the mode's side */
	fprintf(f, "# generated by themer: GRUB's colors, put into /etc/default/grub by themer system sync\n"
	           "GRUB_COLOR_NORMAL=\"%s\"\nGRUB_COLOR_HIGHLIGHT=\"%s\"\n",
	        c->mode == MODE_DARK ? "light-gray/black" : "black/light-gray",
	        c->mode == MODE_DARK ? "black/light-gray" : "white/blue");
}

int
gen_tty(const Config *c, const Scheme *s)
{
	char p[PATH_MAX];

	/* the file from before the system/ directory */
	if (path_under_home(p, sizeof p, ".config/themer/tty.rgb") == 0)
		unlink(p);
	if (gen_at(SYSTEM_DIR "/tty.palette", emit_palette, c, s) < 0)
		return -1;
	return gen_at(SYSTEM_DIR "/console.conf", emit_console, c, s);
}

int
gen_grub(const Config *c, const Scheme *s)
{
	return gen_at(SYSTEM_DIR "/grub.conf", emit_grub, c, s);
}

/* the console escape sequences that set the palette, for env.sh */
void
tty_escapes(const Config *c, char *out, size_t n)
{
	Scheme s;
	char pal[16][7];
	size_t o = 0;

	theme_scheme(c, &s);
	console_palette(&s, pal);
	out[0] = '\0';
	for (int i = 0; i < 16 && o < n; i++)
		o += (size_t)snprintf(out + o, n - o, "\\033]P%X%s", i, pal[i]);
}

/* what Remove all styles takes away: the files the system sync reads (it then puts
 * back what it changed in /etc) */
void
targets_remove(void)
{
	static const char *const files[] = { "tty.palette", "console.conf", "grub.conf" };
	char p[PATH_MAX], rel[64];

	for (size_t i = 0; i < TM_COUNT(files); i++) {
		snprintf(rel, sizeof rel, SYSTEM_DIR "/%s", files[i]);
		if (path_under_home(p, sizeof p, rel) == 0)
			unlink(p);
	}
}

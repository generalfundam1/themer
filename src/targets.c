/* targets.c: built-in targets that are not modules: env, tty, grub. They write
 * system files (tty and grub only as root) that the manifest cannot undo, which is
 * why they are not modules. Everything that touches the user's own config is in
 * modules/. */
#include <limits.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include <unistd.h>
#include "themer.h"

static int
gen_at(const char *rel, EmitFn fn, const Config *c, const Scheme *s)
{
	char p[PATH_MAX];

	if (path_under_home(p, sizeof p, rel) < 0)
		return -1;
	return write_gen(p, fn, c, s);
}

/* ---- environment: systemd user environment, from the [environment] settings ---- */

static void
emit_env(FILE *f, const Config *c, const Scheme *s)
{
	(void)s;
	fprintf(f, "# generated by themer\n");
	for (int i = 0; i < c->nenv; i++)
		fprintf(f, "%s=%s\n", c->env[i].name, c->env[i].value);
}

/* The same variables for sessions that systemd does not start: a script to source
 * from the shell profile before the compositor starts. It reads every themer file in
 * environment.d, the modules' included, so it is never behind them. */
static void
emit_env_sh(FILE *f, const Config *c, const Scheme *s)
{
	(void)c;
	(void)s;
	fprintf(f, "# generated by themer. Source this from ~/.profile (or .zprofile, .bash_profile)\n"
	           "# when your session is not started through systemd, so programs launched by the\n"
	           "# compositor see the variables: . ~/.config/themer/env.sh\n"
	           "for _f in \"${XDG_CONFIG_HOME:-$HOME/.config}\"/environment.d/*themer*.conf; do\n"
	           "\t[ -r \"$_f\" ] || continue\n"
	           "\twhile IFS= read -r _l || [ -n \"$_l\" ]; do\n"
	           "\t\tcase $_l in ''|'#'*) ;; *=*) export \"$_l\" ;; esac\n"
	           "\tdone < \"$_f\"\n"
	           "done\n"
	           "unset _f _l\n");
}

int
gen_env(const Config *c, const Scheme *s)
{
	if (gen_at(".config/environment.d/50-themer.conf", emit_env, c, s) < 0)
		return -1;
	return gen_at(".config/themer/env.sh", emit_env_sh, c, s);
}

/* ---- tty: 16-color kernel palette via setvtrgb, font via vconsole.conf ---- */

static void
hex2rgb(const char *h, unsigned char *rgb)
{
	unsigned long v = strtoul(h, NULL, 16);

	rgb[0] = (v >> 16) & 0xff;
	rgb[1] = (v >> 8) & 0xff;
	rgb[2] = v & 0xff;
}

static void
emit_tty_unit(FILE *f, const Config *c, const Scheme *s)
{
	(void)c;
	(void)s;
	fprintf(f, "[Unit]\nDescription=themer TTY palette\nAfter=local-fs.target\n\n"
	           "[Service]\nType=oneshot\nRemainAfterExit=yes\n"
	           "ExecStart=/usr/bin/setvtrgb /var/lib/themer/tty.rgb\n\n"
	           "[Install]\nWantedBy=multi-user.target\n");
}

int
gen_tty(const Config *c, const Scheme *s)
{
	unsigned char rgb[3 * 256] = { 0 }, v[3];
	char p[PATH_MAX];

	for (int i = 0; i < 16; i++) {
		hex2rgb(s->ansi[i], v);
		rgb[i] = v[0];
		rgb[256 + i] = v[1];
		rgb[512 + i] = v[2];
	}
	if (path_under_home(p, sizeof p, ".config/themer/tty.rgb") < 0 ||
	    write_bytes(p, rgb, sizeof rgb) < 0)
		return -1;
	/* the system part needs root and a running systemd (the unit is enabled with
	 * systemctl); elsewhere only the user's copy is written */
	if (!is_root() || access("/run/systemd/system", F_OK))
		return 0;
	if (write_bytes("/var/lib/themer/tty.rgb", rgb, sizeof rgb) < 0 ||
	    write_gen("/etc/systemd/system/themer-tty.service", emit_tty_unit, c, s) < 0)
		return -1;
	kv_set_file("/etc/vconsole.conf", "FONT", c->tty_font);
	return run("systemctl daemon-reload && systemctl enable --now themer-tty.service >/dev/null 2>&1");
}

/* ---- grub: colors in /etc/default/grub, then regenerate grub.cfg (root only) ---- */

int
gen_grub(const Config *c, const Scheme *s)
{
	char normal[64], high[64];

	(void)s;
	if (!is_root() || access("/etc/default/grub", W_OK) < 0)
		return 0;
	snprintf(normal, sizeof normal, "\"%s\"",
	         c->mode == MODE_DARK ? "light-gray/black" : "black/light-gray");
	snprintf(high, sizeof high, "\"%s\"", "white/blue");
	if (kv_set_file("/etc/default/grub", "GRUB_COLOR_NORMAL", normal) < 0 ||
	    kv_set_file("/etc/default/grub", "GRUB_COLOR_HIGHLIGHT", high) < 0)
		return -1;
	return run("grub-mkconfig -o /boot/grub/grub.cfg >/dev/null 2>&1");
}

#!/bin/sh
# build.sh: makes templates/themer_default/gtk/ from GTK's own Adwaita.
#
#   tools/adwaita/build.sh GTK3_SRC GTK4_SRC [SASS]
#
# GTK3_SRC and GTK4_SRC are GTK source trees (git clone -b gtk-3-24 and -b
# gtk-4-24 of https://gitlab.gnome.org/GNOME/gtk, or its GitHub mirror); SASS is
# dart-sass (default: sass on PATH). The SCSS of GTK 3's Adwaita and GTK 4's
# Default theme is compiled with _themer.scss, which leaves the colors as GTK
# expressions over a few named colors; the header each file gets defines those
# from the theme with {{variables}}. Re-run it to follow a new GTK release.
#
# Writes, in templates/themer_default/gtk/:
#   gtk.css, gtk-dark.css      GTK 3: Adwaita and Adwaita-dark (GTK 3 picks the
#                              dark one when prefer-dark is set, which themer
#                              sets in dark mode)
#   gtk4.css, gtk4-dark.css    the same from GTK 4's Default theme
set -eu

here=$(cd "$(dirname "$0")" && pwd)
root=$(cd "$here/../.." && pwd)
gtk3=${1:?usage: build.sh GTK3_SRC GTK4_SRC [SASS]}
gtk4=${2:?usage: build.sh GTK3_SRC GTK4_SRC [SASS]}
sass=${3:-sass}
out="$root/templates/themer_default/gtk"
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT

# the base colors: each Adwaita variable becomes a symbol for a themer color
base() {
	sed -E \
	    -e 's/^\$(base_color|text_color|bg_color|fg_color|selected_fg_color|selected_bg_color|warning_color|error_color|success_color|destructive_color): (.*);$/$\1: sym("@themer_\1", \2);/' \
	    "$1"
}

# every other variable of _colors.scss: named once, so the output refers to it
names() {
	awk '{ print }
	     /^[ \t]*\$[a-z_]+:.*;[ \t]*$/ {
	         match($0, /\$[a-z_]+/); v = substr($0, RSTART + 1, RLENGTH - 1)
	         ind = $0; sub(/\$.*/, "", ind)
	         if (v != "variant" && v != "contrast")
	             printf "%s$%s: named(\"%s\", $%s);\n", ind, v, v, v
	     }'
}

# Where Adwaita draws on plain white rather than a color of its palette: the
# unchecked check and radio boxes (white on the light side), and the text of the
# suggested and destructive buttons. Here they are the view color and the text
# chosen for the accent and the urgent color.
surfaces() {
	sed -E \
	    -e "s/\\\$_c: if\(\\\$variant ?== ?'light', white, \\\$bg_color\);/\$_c: if(\$variant == 'light', \$base_color, \$bg_color);/" \
	    -e 's/@include button\(([a-z-]+), \$b_color, white\)/@include button(\1, $b_color, if($b_color == $destructive_color, $themer_on_destructive_color, $selected_fg_color))/' \
	    "$1"
}

# compile: $1 source dir, $2 variant, $3 output, $4 asset url prefix, $5 header
build() {
	src=$1 variant=$2 dst=$3 assets=$4 header=$5
	w="$work/$(basename "$dst" .css)"
	mkdir -p "$w"
	cp "$src"/_*.scss "$w/"
	cp "$here/_themer.scss" "$w/"
	base "$src/_colors.scss" | names > "$w/_colors.scss"
	surfaces "$src/_common.scss" > "$w/_common.scss"
	printf '$variant: "%s";\n$contrast: "normal";\n@import "themer";\n@import "colors";\n@include themer-defs;\n@import "drawing";\n@import "common";\n@import "colors-public";\n' \
	    "$variant" > "$w/main.scss"
	"$sass" --quiet --no-source-map --no-charset --style=expanded "$w/main.scss" "$w/out.css"
	{
		cat "$header"
		# GTK 4.16 took CSS's relative colors; older GTK 4 reads only its own
		# functions, which say the same thing here
		sed -E -e 's/@@#[0-9A-Fa-f]{8}//g' \
		       -e 's/rgb\(from ([^ ]+) r g b \/ calc\(alpha \* ([0-9.]+)\)\)/alpha(\1, \2)/g' \
		       -e 's/hsl\(from ([^ ]+) h calc\(s \* ([0-9.]+)\) calc\(l \* \2\)\)/shade(\1, \2)/g' \
		       -e "s#url\\(\"assets/#url(\"$assets/#g" "$w/out.css"
	} > "$dst"
	# the template engine reads {{ as a variable
	if grep -n '{{' "$w/out.css" >/dev/null; then
		echo "build.sh: $dst: '{{' in the compiled CSS" >&2
		exit 1
	fi
	if grep -nE '(rgb|hsl|oklab|oklch)\(from ' "$dst" >&2; then
		echo "build.sh: $dst: a relative color older GTK cannot read (above)" >&2
		exit 1
	fi
	echo "$dst: $(wc -c < "$dst") bytes"
}

header() {
	# $1 GTK version, $2 variant, $3 file
	cat > "$3" <<EOF
/* generated by themer: GTK $1's Adwaita ($2) in the theme's colors.
 * Made by tools/adwaita/build.sh from GTK's own SCSS: change the colors here,
 * the rest by re-running it. Every color below comes from these. */
@define-color themer_bg_color #{{bg}};
@define-color themer_fg_color #{{fg}};
@define-color themer_base_color #{{view}};
@define-color themer_text_color #{{fg}};
@define-color themer_selected_bg_color #{{acc}};
@define-color themer_selected_fg_color #{{accfg}};
@define-color themer_warning_color #{{warn}};
@define-color themer_error_color #{{urg}};
@define-color themer_destructive_color #{{urg}};
@define-color themer_success_color #{{ansi2}};
@define-color themer_on_destructive_color #{{on_urg}};
@define-color themer_fg @themer_fg_color;
@define-color themer_bg @themer_bg_color;

EOF
}

mkdir -p "$out"
for v in light dark; do
	header 3 $v "$work/h3-$v"
	header 4 $v "$work/h4-$v"
	suffix=$([ $v = dark ] && echo -dark || true)
	build "$gtk3/gtk/theme/Adwaita" $v "$out/gtk$suffix.css" \
	      "resource:///org/gtk/libgtk/theme/Adwaita/assets" "$work/h3-$v"
	build "$gtk4/gtk/theme/Default" $v "$out/gtk4$suffix.css" \
	      "resource:///org/gtk/libgtk/theme/Default/assets" "$work/h4-$v"
done

/* ---- the modules page: the list on the left, the selected module on the right,
 * its options in the sections every front end uses (front_option_group). A switch
 * loads or unloads at once and an option takes effect at once, as in the TUI and
 * themer-web; Apply is for the theme, fonts, icons and cursor. ---- */

typedef struct { int module, option; } OptRef;

static GtkWidget *mod_list, *mod_detail, *mod_state[MAX_MODULES];
static int mod_sel = -1;
static OptRef optrefs[MAX_OPTS];
static void on_opt_action(GtkButton *b, gpointer data);

static void module_detail(void);

static gboolean
rebuild_detail(gpointer data)
{
	(void)data;
	module_detail();
	return G_SOURCE_REMOVE;
}

/* the detail is rebuilt after the signal that changed it has returned */
static void
later_rebuild(void)
{
	g_idle_add(rebuild_detail, NULL);
}

static const char *
module_state_text(int i)
{
	return front_module_state(&cfg, i);
}

static int filling_modules;
static GtkWidget *sel_row, *mod_list_scroll;   /* the selected module's row, to scroll to */

/* The list in the groups every front end shows (loaded, unloaded, not installed),
 * a heading row before each; refilled when a module changes group. Each module's
 * row carries its index + 1 as "module"; headings carry none and cannot be picked. */
static void
refresh_module_states(void)
{
	GList *old = gtk_container_get_children(GTK_CONTAINER(mod_list));

	filling_modules++;
	for (GList *l = old; l; l = l->next)
		gtk_widget_destroy(l->data);
	g_list_free(old);
	memset(mod_state, 0, sizeof mod_state);
	nmodule_order = front_module_order(&cfg, module_order, MAX_MODULES);
	for (int k = 0, last = -1; k < nmodule_order; k++) {
		int i = module_order[k];
		GtkWidget *row, *box, *name;

		if (front_module_group(&cfg, i) != last) {
			GtkWidget *h = heading(front_module_group_title(last = front_module_group(&cfg, i)));

			row = gtk_list_box_row_new();
			gtk_list_box_row_set_selectable(GTK_LIST_BOX_ROW(row), FALSE);
			gtk_list_box_row_set_activatable(GTK_LIST_BOX_ROW(row), FALSE);
			gtk_widget_set_margin_start(h, 4);
			gtk_container_add(GTK_CONTAINER(row), h);
			gtk_list_box_insert(GTK_LIST_BOX(mod_list), row, -1);
		}
		row = gtk_list_box_row_new();
		box = gtk_box_new(GTK_ORIENTATION_HORIZONTAL, 8);
		name = gtk_label_new(themer_module_name(i));
		gtk_widget_set_halign(name, GTK_ALIGN_START);
		gtk_widget_set_sensitive(name, themer_module_present(&cfg, i));
		mod_state[i] = caption(module_state_text(i));
		gtk_box_pack_start(GTK_BOX(box), name, TRUE, TRUE, 0);
		gtk_box_pack_end(GTK_BOX(box), mod_state[i], FALSE, FALSE, 0);
		gtk_container_set_border_width(GTK_CONTAINER(box), 4);
		gtk_container_add(GTK_CONTAINER(row), box);
		g_object_set_data(G_OBJECT(row), "module", GINT_TO_POINTER(i + 1));
		gtk_list_box_insert(GTK_LIST_BOX(mod_list), row, -1);
		if (i == mod_sel) {
			gtk_list_box_select_row(GTK_LIST_BOX(mod_list), GTK_LIST_BOX_ROW(row));
			sel_row = row;
		}
	}
	gtk_widget_show_all(mod_list);
	filling_modules--;
}

static gboolean
focus_sel_row(gpointer data)
{
	(void)data;
	int y;

	/* the list alone scrolls to it, not the page around it */
	if (sel_row && mod_list_scroll && gtk_widget_translate_coordinates(sel_row, mod_list, 0, 0, NULL, &y))
		gtk_adjustment_clamp_page(gtk_scrolled_window_get_vadjustment(GTK_SCROLLED_WINDOW(mod_list_scroll)),
		                          y, y + gtk_widget_get_allocated_height(sel_row));
	return G_SOURCE_REMOVE;
}

/* selects module i in the list (the command line's themer-gtk modules NAME) */
static void
select_module(int i)
{
	mod_sel = i;
	refresh_module_states();
	module_detail();
	g_timeout_add(200, focus_sel_row, NULL);   /* once the list has its size */
}

/* sets an option; it takes effect at once */
static void
set_opt(const OptRef *o, const char *value)
{
	char msg[256];

	if (updating || !strcmp(value, themer_option_value(&cfg, o->module, o->option)))
		return;
	front_option_set(&cfg, o->module, o->option, value, msg, sizeof msg);
	set_status(msg);
	restyle();
	later_rebuild();
}

static void
on_opt_combo(GtkComboBox *c, gpointer data)
{
	const char *id = gtk_combo_box_get_active_id(c);   /* a set: its directory name */
	gchar *t = id ? NULL : gtk_combo_box_text_get_active_text(GTK_COMBO_BOX_TEXT(c));

	if (id || t)
		set_opt(data, id ? id : t);
	g_free(t);
}

/* a slider takes effect once it rests, not at every step of a drag (each step
 * would reload the module and rebuild the page under the pointer) */
static guint scale_timer;
static char scale_value[16];
static const OptRef *scale_ref;

static gboolean
scale_commit(gpointer data)
{
	(void)data;
	scale_timer = 0;
	if (scale_ref)
		set_opt(scale_ref, scale_value);
	return G_SOURCE_REMOVE;
}

static void
on_opt_scale(GtkRange *r, gpointer data)
{
	if (updating)
		return;
	snprintf(scale_value, sizeof scale_value, "%d", (int)gtk_range_get_value(r));
	scale_ref = data;
	if (scale_timer)
		g_source_remove(scale_timer);
	scale_timer = g_timeout_add(400, scale_commit, NULL);
}

